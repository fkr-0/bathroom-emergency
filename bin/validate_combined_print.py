#!/usr/bin/env python3
"""Regression checks for the bound/combined printable guide.

The master is intentionally one Chromium document so it stays tagged and keeps
working links/outlines. These checks protect the two properties that previously
drifted from the standalone books: cover rendering and per-book running
furniture.
"""
from __future__ import annotations

import json
import re
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageChops, ImageStat

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
MANIFEST = json.loads((ROOT / "src" / "data" / "subguides.json").read_text(encoding="utf-8"))
NODES = MANIFEST["nodes"]
errors: list[str] = []

VARIANTS = (
    ("guide", "a4", "color", "A4 / color"),
    ("guide_mono", "a4", "mono", "A4 / mono"),
    ("guide_a4half", "a4half", "color", "A4/2 / color"),
    ("guide_a4half_mono", "a4half", "mono", "A4/2 / mono"),
    ("guide_largeprint", "largeprint", "color", "LARGE PRINT / color"),
    ("guide_largeprint_mono", "largeprint", "mono", "LARGE PRINT / mono"),
)


def check(condition: bool, message: str) -> None:
    if not condition:
        errors.append(message)


def run(*args: str) -> str:
    result = subprocess.run(args, cwd=ROOT, capture_output=True, text=True)
    if result.returncode:
        errors.append(f"command failed: {' '.join(args)} — {(result.stderr or result.stdout).strip()}")
        return ""
    return result.stdout


def pdf_pages(path: Path) -> list[str]:
    return run("pdftotext", "-layout", str(path), "-").split("\f")


def normalized(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def top_region(page: str) -> str:
    # Margin-box text is emitted before body text. Twelve physical lines leave
    # room for a wrapped narrow A4/2 title but do not reach normal body prose.
    return normalized("\n".join(page.splitlines()[:12]))


def variant_suffix(layout: str, mode: str) -> str:
    parts: list[str] = []
    if layout != "a4":
        parts.append(layout)
    if mode == "mono":
        parts.append("mono")
    return "_" + "_".join(parts) if parts else ""


def first_page_text(path: Path) -> str:
    return normalized(run("pdftotext", "-f", "1", "-l", "1", "-layout", str(path), "-"))


def cover_page(pages: list[str], marker: str) -> int | None:
    hits = [index for index, page in enumerate(pages, start=1) if marker in page]
    check(len(hits) == 1, f"combined A4 cover marker {marker!r} occurs on pages {hits}")
    return hits[0] if len(hits) == 1 else None


def raster_rms(master: Path, master_page: int, standalone: Path) -> float | None:
    with tempfile.TemporaryDirectory(prefix="beg-combined-cover-") as directory:
        tmp = Path(directory)
        master_prefix = tmp / "master"
        single_prefix = tmp / "single"
        for pdf, page, prefix in (
            (master, master_page, master_prefix),
            (standalone, 1, single_prefix),
        ):
            result = subprocess.run(
                [
                    "pdftoppm", "-f", str(page), "-l", str(page), "-singlefile",
                    "-png", "-r", "72", str(pdf), str(prefix),
                ],
                cwd=ROOT,
                capture_output=True,
                text=True,
            )
            if result.returncode:
                errors.append(
                    f"cover raster failed for {pdf.relative_to(ROOT)}: "
                    f"{(result.stderr or result.stdout).strip()}"
                )
                return None
        left = Image.open(master_prefix.with_suffix(".png")).convert("RGB")
        right = Image.open(single_prefix.with_suffix(".png")).convert("RGB")
        if left.size != right.size:
            errors.append(
                f"cover raster geometry differs: combined={left.size}, standalone={right.size}"
            )
            return None
        rms = ImageStat.Stat(ImageChops.difference(left, right)).rms
        return sum(rms) / len(rms)


markdown = BUILD / "md" / "guide.md"
if markdown.exists():
    text = markdown.read_text(encoding="utf-8")
    check('.document-cover' not in text, "legacy document-cover returned to combined markdown")
    check('data-subguide="SHELF"' in text, "combined markdown does not start from the Shelf book")
    check(text.count('.standalone-subguide') == 12, "combined markdown is not Shelf + eleven book wrappers")
else:
    errors.append("combined markdown is missing")

# Generated CSS must route every book to a named page. The literal header text
# is generated by project_meta.revision_footer_css for the same node metadata
# used by standalone editions.
for stem, _layout, _mode, _token in VARIANTS:
    css_name = stem.replace("_", "-") + ".css"
    css_path = BUILD / "html" / css_name
    if not css_path.exists():
        errors.append(f"missing combined CSS: {css_path.relative_to(ROOT)}")
        continue
    css = css_path.read_text(encoding="utf-8")
    check("@page beg-cover" in css, f"{css_name}: cover page reset missing")
    check('data-subguide="SHELF"' in css and "page: beg-shelf" in css, f"{css_name}: Shelf page route missing")
    for node in NODES:
        page_name = f'beg-{node["id"].lower()}'
        check(f"@page {page_name}" in css, f"{css_name}: named page missing for {node['id']}")
        check(f"page: {page_name}" in css, f"{css_name}: page assignment missing for {node['id']}")

for stem, layout, mode, edition in VARIANTS:
    pdf = BUILD / "pdf" / f"{stem}.pdf"
    if not pdf.exists():
        errors.append(f"missing combined PDF: {pdf.relative_to(ROOT)}")
        continue
    info = run("pdfinfo", str(pdf))
    check(re.search(r"^Tagged:\s+yes$", info, re.M) is not None, f"{stem}: PDF lost tagging")
    pages = pdf_pages(pdf)
    first = normalized(pages[0]) if pages else ""
    check("START HERE · 11 BOOKS" in first, f"{stem}: Shelf cover is not page one")
    check("SMALL-ROOM FIELD NOTES" not in first, f"{stem}: legacy master cover returned")
    check(edition not in first, f"{stem}: running furniture leaked onto Shelf cover")

    shelf_suffix = variant_suffix(layout, mode)
    shelf_pdf = BUILD / "subguides" / "SHELF" / f"shelf-how-to-use{shelf_suffix}.pdf"
    if shelf_pdf.exists():
        check(
            normalized(pages[0]) == first_page_text(shelf_pdf),
            f"{stem}: Shelf cover text differs from standalone Shelf edition",
        )

    for position, node_id in enumerate(MANIFEST["shelf_order"], start=1):
        node = next(item for item in NODES if item["id"] == node_id)
        marker = f"BOOK {position} OF {len(MANIFEST['shelf_order'])}"
        hits = [index for index, page in enumerate(pages, start=1) if marker in normalized(page)]
        check(len(hits) == 1, f"{stem}: {node_id} cover marker occurs on pages {hits}")
        if hits:
            check(edition not in pages[hits[0] - 1], f"{stem}: running furniture leaked onto {node_id} cover")

        title = normalized(node["title"])
        header_hits = [
            index
            for index, page in enumerate(pages, start=1)
            if title in top_region(page) and edition in top_region(page)
        ]
        check(bool(header_hits), f"{stem}: custom running header missing for {node_id} — {node['title']}")

# Raster parity is intentionally limited to representative A4 colour covers;
# the six-edition text/route checks above cover the matrix, while these catch
# padding, pattern, border and page-box regressions that text extraction cannot.
a4_pdf = BUILD / "pdf" / "guide.pdf"
if a4_pdf.exists():
    a4_pages = pdf_pages(a4_pdf)
    shelf_single = BUILD / "subguides" / "SHELF" / "shelf-how-to-use.pdf"
    green = next(node for node in NODES if node["id"] == "O")
    green_single = BUILD / "subguides" / "O" / f'{green["slug"]}.pdf'
    green_page = cover_page(a4_pages, "BOOK 1 OF 11")
    for label, page, standalone in (
        ("Shelf", 1, shelf_single),
        ("Green", green_page, green_single),
    ):
        if page is None or not standalone.exists():
            errors.append(f"{label}: standalone cover unavailable for raster parity")
            continue
        rms = raster_rms(a4_pdf, page, standalone)
        if rms is not None:
            check(rms < 0.25, f"{label}: combined/standalone cover raster drifted (RMS {rms:.3f})")

if errors:
    raise SystemExit("Combined-print validation failed:\n- " + "\n- ".join(errors))

print(
    "Combined-print validation passed: Shelf + eleven covers, per-book named-page "
    "headers across six editions, tagged PDFs, and representative raster parity."
)
